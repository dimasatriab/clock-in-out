const ADDED_COLUMNS = [
  ['attendance', 'out_auto', 'INTEGER NOT NULL DEFAULT 0'],
  ['face_samples', 'pose', 'TEXT'],
  ['face_samples', 'quality_score', 'REAL'],
  ['face_samples', 'sharpness', 'REAL'],
  ['face_samples', 'yaw', 'REAL'],
  ['face_samples', 'pitch', 'REAL'],
  ['admins', 'must_change_password', 'INTEGER NOT NULL DEFAULT 0'],
  ['admins', 'phone', 'TEXT'],
  ['admins', 'pin_hash', 'TEXT']
];

function columnNames(db, table) {
  return db.prepare(`PRAGMA table_info(${table})`).all().map((row) => row.name);
}

function addColumn(db, table, column, definition) {
  const tables = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?").get(table);
  if (!tables) return;
  if (columnNames(db, table).includes(column)) return;
  db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
}

export function migrateSqlite(db) {
  db.exec(`CREATE TABLE IF NOT EXISTS login_attempts (
    key TEXT PRIMARY KEY,
    failures INTEGER NOT NULL,
    locked_until TEXT
  )`);
  db.exec(`CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  )`);
  db.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    id TEXT PRIMARY KEY,
    applied_at TEXT NOT NULL
  )`);
  const done = new Set(db.prepare('SELECT id FROM schema_migrations').all().map((row) => row.id));
  const mark = db.prepare('INSERT INTO schema_migrations (id, applied_at) VALUES (?, ?)');
  const now = new Date().toISOString();
  const settingsId = '004_settings_quality_auto_clockout';
  if (!done.has(settingsId)) {
    for (const [table, column, definition] of ADDED_COLUMNS) addColumn(db, table, column, definition);
    mark.run(settingsId, now);
  }
  const everywhereId = '005_everywhere';
  if (!done.has(everywhereId)) {
    addColumn(db, 'employees', 'everywhere', 'INTEGER NOT NULL DEFAULT 0');
    addColumn(db, 'locations', 'scope', "TEXT NOT NULL DEFAULT 'place'");
    mark.run(everywhereId, now);
  }
  const deleteId = '006_soft_delete';
  if (!done.has(deleteId)) {
    addColumn(db, 'employees', 'deleted_at', 'TEXT');
    addColumn(db, 'locations', 'deleted_at', 'TEXT');
    mark.run(deleteId, now);
  }
}

